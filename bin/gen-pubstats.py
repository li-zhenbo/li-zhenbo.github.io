#!/usr/bin/env python3
"""Count publications by type from _bibliography/papers.bib, output _data/pubstats.yml."""
import re, sys, os
from collections import Counter

bibfile = os.path.join(os.path.dirname(__file__), "..", "_bibliography", "papers.bib")
outfile = os.path.join(os.path.dirname(__file__), "..", "_data", "pubstats.yml")

if not os.path.isfile(bibfile):
    print(f"ERROR: {bibfile} not found", file=sys.stderr)
    sys.exit(1)

with open(bibfile) as f:
    content = f.read()

# Count entry types
types = Counter()
types["article"] = len(re.findall(r"^@article\s*\{", content, re.M))
types["inproceedings"] = len(re.findall(r"^@inproceedings\s*\{", content, re.M))
types["book"] = len(re.findall(r"^@book\s*\{", content, re.M))
types["misc"] = len(re.findall(r"^@misc\s*\{", content, re.M))

# Extract years
years = [int(y) for y in re.findall(r"^\s*year\s*=\s*\{(\d{4})\}", content, re.M)]
year_min = min(years) if years else 0
year_max = max(years) if years else 0

os.makedirs(os.path.dirname(outfile), exist_ok=True)
with open(outfile, "w") as f:
    f.write("# Auto-generated by bin/gen-pubstats.py — DO NOT EDIT\n")
    f.write(f"journals: {types['article']}\n")
    f.write(f"conferences: {types['inproceedings']}\n")
    f.write(f"monographs: {types['book']}\n")
    f.write(f"total: {sum(types.values())}\n")
    f.write(f"year_start: {year_min}\n")
    f.write(f"year_end: {year_max}\n")
    f.write(f"year_span: {year_max - year_min + 1 if years else 0}\n")

print(f"Written {outfile}: {dict(types)}, years {year_min}-{year_max}")
